import sys
import os
import random
from datetime import datetime, timedelta

sys.path.append(os.path.dirname(os.path.abspath(__file__)))

from app.core.database import SessionLocal
from app.models.user import User
from app.models.pipeline_stage import PipelineStage
from app.models.deal import Deal

STAGES = [
    {"stage_key": "new", "label": "New", "sort_order": 10},
    {"stage_key": "discovery", "label": "Discovery", "sort_order": 20},
    {"stage_key": "proposal", "label": "Proposal", "sort_order": 30},
    {"stage_key": "negotiation", "label": "Negotiation", "sort_order": 40},
    {"stage_key": "won", "label": "Closed Won", "sort_order": 50, "is_closed_won": True},
    {"stage_key": "lost", "label": "Closed Lost", "sort_order": 60, "is_closed_lost": True},
]

def seed_db():
    db = SessionLocal()
    try:
        # 1. Seed Pipeline Stages
        print("Seeding pipeline stages...")
        for stage_data in STAGES:
            existing = db.query(PipelineStage).filter_by(stage_key=stage_data["stage_key"]).first()
            if not existing:
                db.add(PipelineStage(**stage_data))
        db.commit()
        print("Pipeline stages seeded successfully!")

        # 2. Seed Deals
        print("Seeding deals...")
        users = db.query(User).all()
        if not users:
            print("No users found to assign deals to. Please add users first.")
            return

        stages = db.query(PipelineStage).all()
        
        deals_to_create = []
        for user in users:
            # Let's create 3 deals for each user
            for i in range(3):
                stage = random.choice(stages)
                outcome = "open"
                if stage.is_closed_won: outcome = "won"
                elif stage.is_closed_lost: outcome = "lost"
                
                deals_to_create.append(Deal(
                    owner_id=user.id,
                    title=f"Sample Deal {i+1} for {user.name}",
                    stage_id=stage.id,
                    amount=random.randint(10000, 500000),
                    currency="INR",
                    probability=random.randint(10, 90),
                    expected_close_date=datetime.utcnow() + timedelta(days=random.randint(10, 60)),
                    outcome=outcome,
                    notes="Generated by seed script."
                ))
        
        db.add_all(deals_to_create)
        db.commit()
        print(f"Created {len(deals_to_create)} deals successfully!")
        
    except Exception as e:
        db.rollback()
        print(f"Error seeding data: {e}")
    finally:
        db.close()

if __name__ == "__main__":
    seed_db()
